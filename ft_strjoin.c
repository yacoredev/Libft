#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	char	*concat;
	size_t	size;

	if (!s1 || !s2)
		return (NULL);
	size = ft_strlen(s1) + ft_strlen(s2) + 1;
	concat = malloc(size);
	if (!concat)
		return (NULL);
	ft_strlcpy(concat, s1, size);
	ft_strlcat(concat, s2, size);
	return (concat);
}
